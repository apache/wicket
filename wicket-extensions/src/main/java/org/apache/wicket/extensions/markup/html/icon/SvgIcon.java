	/**
	 * @return the icon as an {@code svg} element with the class {@code wicket-svg-icon}
	 * @throws WicketRuntimeException
	 *             if the Font Awesome web jar is not on the class path
	 */
	@Override
	public String getMarkup()
	{
		return Markup.ICONS.computeIfAbsent(this, Markup::load);
	}

	private static final class Markup
	{
		private static final String WEBJAR =
			"META-INF/resources/webjars/fortawesome__fontawesome-free/";

		private static final Pattern SVG = Pattern.compile(
			"<svg[^>]*\\sviewBox=\"0 0 (\\d+) (\\d+)\"[^>]*>(.*)</svg>\\s*", Pattern.DOTALL);

		private static final Map<SvgIcon, String> ICONS = new ConcurrentHashMap<>();

		private static String load(SvgIcon icon)
		{
			String name = FontAwesomeIcon.valueOf(icon.name()).getName();
			String file = WEBJAR + version() + "/svgs/solid/" + name + ".svg";
			String svg;
			try (InputStream in = SvgIcon.class.getClassLoader().getResourceAsStream(file))
			{
				if (in == null)
				{
					throw new WicketRuntimeException("Font Awesome has no icon " + file);
				}
				svg = new String(in.readAllBytes(), StandardCharsets.UTF_8);
			}
			catch (IOException e)
			{
				throw new WicketRuntimeException("Cannot read " + file, e);
			}
			Matcher matcher = SVG.matcher(svg);
			if (!matcher.matches())
			{
				throw new WicketRuntimeException("Unexpected content in " + file);
			}
			String width = matcher.group(1);
			String height = matcher.group(2);
			String em = Double.toString(Integer.parseInt(width) / Double.parseDouble(height));
			return "<svg class=\"wicket-svg-icon\" aria-hidden=\"true\" focusable=\"false\" " +
				"viewBox=\"0 0 " + width + " " + height + "\" width=\"" + em +
				"em\" height=\"1em\" fill=\"currentColor\">" + matcher.group(3) + "</svg>";
		}

		private static String version()
		{
			try (InputStream in = SvgIcon.class.getClassLoader().getResourceAsStream(
				"META-INF/maven/org.webjars.npm/fortawesome__fontawesome-free/pom.properties"))
			{
				if (in == null)
				{
					throw new WicketRuntimeException("SvgIcon needs the Font Awesome Free web jar " +
						"(org.webjars.npm:fortawesome__fontawesome-free) on the class path");
				}
				Properties properties = new Properties();
				properties.load(in);
				return properties.getProperty("version");
			}
			catch (IOException e)
			{
				throw new WicketRuntimeException("Cannot read the Font Awesome web jar version", e);
			}
		}
	}
